import AppKit
import Foundation

/// What a Smart Paste found on the clipboard.
enum ClipContent: Equatable, Sendable {
    case text(String)
    /// An image with no text alongside it. Read as raw PNG or TIFF data.
    case image(Data)
    case empty
    /// The clipboard holds something that must never be read, such as a password.
    case refused(ClipRefusal)
}

enum ClipRefusal: String, Equatable, Sendable {
    /// Marked concealed by a password manager.
    case concealed
    /// Marked transient: a value only meant to pass through, often our own in-flight paste.
    case transient
    /// Generated by an app rather than copied by the user.
    case autoGenerated

    var message: String {
        switch self {
        case .concealed: "The clipboard holds a password, so Smart Paste will not read it"
        case .transient, .autoGenerated: "The clipboard holds something not meant to be kept, so it was not read"
        }
    }
}

/// Reads the clipboard for a Smart Paste, honouring the markers clipboard managers honour.
///
/// The nspasteboard.org markers are the convention password managers and clipboard tools agree
/// on. An app that marks a copy concealed is saying "this is a secret"; reading it into a
/// prompt would be exactly the leak the marker exists to prevent.
enum ClipboardReader {
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Image flavours worth reading, most specific first.
    static let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff]

    /// Reads `pasteboard` without changing it. Takes the pasteboard as a parameter so tests use
    /// a private named one and never touch the user's real clipboard.
    @MainActor
    static func read(from pasteboard: NSPasteboard = .general) -> ClipContent {
        let items = pasteboard.pasteboardItems ?? []
        let types = Set(items.flatMap(\.types))

        if types.contains(concealedType) { return .refused(.concealed) }
        if types.contains(transientType) { return .refused(.transient) }
        if types.contains(autoGeneratedType) { return .refused(.autoGenerated) }

        // Browsers copy an image together with its address or alt text. When there is text,
        // the text is what the user means to paste.
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(text)
        }
        for type in imageTypes {
            if let data = pasteboard.data(forType: type), !data.isEmpty {
                return .image(data)
            }
        }
        return .empty
    }
}
