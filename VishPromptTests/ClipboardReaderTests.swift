import AppKit
import XCTest
@testable import VishPrompt

/// Runs against a real pasteboard, but a private named one: the user's clipboard is never read
/// or written by these tests.
@MainActor
final class ClipboardReaderTests: XCTestCase {
    private var pasteboard: NSPasteboard!

    override func setUp() async throws {
        pasteboard = NSPasteboard(name: NSPasteboard.Name("vishprompt.tests.\(UUID().uuidString)"))
        pasteboard.clearContents()
    }

    override func tearDown() async throws {
        pasteboard.releaseGlobally()
        pasteboard = nil
    }

    private func write(_ entries: [(NSPasteboard.PasteboardType, Data)]) {
        let item = NSPasteboardItem()
        for (type, data) in entries { item.setData(data, forType: type) }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
    }

    private let png = NSBitmapImageRep(
        bitmapDataPlanes: nil, pixelsWide: 2, pixelsHigh: 2, bitsPerSample: 8, samplesPerPixel: 4,
        hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0
    )!.representation(using: .png, properties: [:])!

    func testPlainTextIsRead() {
        pasteboard.setString("hello there", forType: .string)
        XCTAssertEqual(ClipboardReader.read(from: pasteboard), .text("hello there"))
    }

    func testConcealedIsRefused() {
        write([(.string, Data("hunter2".utf8)), (ClipboardReader.concealedType, Data())])
        XCTAssertEqual(ClipboardReader.read(from: pasteboard), .refused(.concealed))
    }

    func testTransientIsRefused() {
        write([(.string, Data("passing through".utf8)), (ClipboardReader.transientType, Data())])
        XCTAssertEqual(ClipboardReader.read(from: pasteboard), .refused(.transient))
    }

    func testAutoGeneratedIsRefused() {
        write([(.string, Data("made by an app".utf8)), (ClipboardReader.autoGeneratedType, Data())])
        XCTAssertEqual(ClipboardReader.read(from: pasteboard), .refused(.autoGenerated))
    }

    func testImageAndTextGivesTheText() {
        write([(.png, png), (.string, Data("https://example.com/cat.png".utf8))])
        XCTAssertEqual(ClipboardReader.read(from: pasteboard), .text("https://example.com/cat.png"))
    }

    func testImageAloneIsAnImage() {
        write([(.png, png)])
        XCTAssertEqual(ClipboardReader.read(from: pasteboard), .image(png))
    }

    func testEmptyAndWhitespaceAreEmpty() {
        XCTAssertEqual(ClipboardReader.read(from: pasteboard), .empty)
        pasteboard.setString("   \n", forType: .string)
        XCTAssertEqual(ClipboardReader.read(from: pasteboard), .empty)
    }

    func testReadingDoesNotChangeTheClipboard() {
        pasteboard.setString("keep me", forType: .string)
        let before = pasteboard.changeCount
        _ = ClipboardReader.read(from: pasteboard)
        XCTAssertEqual(pasteboard.changeCount, before)
    }
}
